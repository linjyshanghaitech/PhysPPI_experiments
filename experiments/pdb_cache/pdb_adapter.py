#!/usr/bin/env python3
"""Training-time adapter: load pre-computed PDB caches into the PhysPPI pipeline.

Replaces on-the-fly PDB parsing + atom canonicalization with fast
``torch.load`` calls.

Cache format (generated by ``generate_pdb_tensors.py``)::

    {case_id}_gt.pt                  canonized GT AtomArray
    {case_id}_{chain}_monomer.pt     processed monomer AtomArray per chain
    {case_id}_seq.pt                 per-chain sequence metadata

All three use ``torch.save`` / ``torch.load`` for consistency with
the existing mesh / residue prior caches.

Usage in ``_runtime.py`` (future integration)::

    from experiments.pdb_cache.pdb_adapter import (
        load_gt_atom_array,
        load_monomer_atom_arrays,
        load_seq_cache_data,
        extract_template_precursor,
    )

    # --- GT ---
    gt_aa = load_gt_atom_array(pt_dir / f"{case_id}_gt.pt")
    # → AtomArray, ready for process_target_atom_array_of3(crop)

    # --- Monomers ---
    monomer_aas = load_monomer_atom_arrays(
        pt_dir, case_id, chain_ids=["A", "B"]
    )
    # → {"A": AtomArray, "B": AtomArray}

    # --- Template precursor (extracted on-the-fly from loaded AtomArrays) ---
    precursor = extract_template_precursor(monomer_aas)
    # → {"A": {...}, "B": {...}} with per-residue pseudo_beta, backbone coords

    # --- Seq cache ---
    seq = load_seq_cache_data(pt_dir / f"{case_id}_seq.pt")
    # → {"A": {"full_seq_1aa": ..., "full_seq_3aa": [...]}, ...}
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import numpy as np
import torch

# -- Ensure the PhysPPI repo root is on sys.path --
_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from biotite.structure import AtomArray  # noqa: E402
from biotite.structure.bonds import BondList  # noqa: E402


# --- AtomArray ↔ .pt serialization -------------------------------------------


def save_atomarray_as_pt(atom_array: AtomArray, path: Path) -> None:
    """Save a biotite AtomArray as a ``.pt`` file via ``torch.save``.

    All annotations (chain_id, res_id, res_name, atom_name, coord,
    element, entity_id, token_id, ...) are preserved.

    *coord* is stored as ``torch.Tensor`` for fast I/O.
    All other annotations are stored as raw ``numpy.ndarray`` (via pickle
    inside ``torch.save``) to preserve exact dtypes — especially
    fixed-width Unicode string dtypes like ``U4``.
    """
    data: dict[str, Any] = {}

    # Coordinates — store as tensor for speed
    data["coord"] = torch.from_numpy(
        np.asarray(atom_array.coord, dtype=np.float32).copy()
    )

    # Bonds (rare in PhysPPI PDBs but preserved for completeness)
    if atom_array.bonds is not None:
        data["bonds"] = atom_array.bonds.as_array().copy()

    # All other annotation categories — keep as raw numpy to preserve dtype
    for ann in atom_array.get_annotation_categories():
        val = getattr(atom_array, ann)
        arr = np.asarray(val)
        data[ann] = arr.copy()

    tmp = path.with_suffix(path.suffix + ".tmp")
    torch.save(data, tmp)
    tmp.replace(path)


def load_atomarray_from_pt(path: Path) -> AtomArray:
    """Load a biotite AtomArray from a ``.pt`` file.

    Inverse of ``save_atomarray_as_pt``.
    """
    data = torch.load(path, map_location="cpu", weights_only=False)
    n_atoms = data["coord"].shape[0]
    atom_array = AtomArray(n_atoms)

    for key, val in data.items():
        if key == "coord":
            atom_array.coord = val.numpy()
        elif key == "bonds":
            atom_array.bonds = BondList(n_atoms, val)
        elif isinstance(val, np.ndarray):
            # All other annotations — set directly (dtype preserved)
            atom_array.set_annotation(key, val)
        elif isinstance(val, torch.Tensor):
            # Legacy: older .pt files may have tensor annotations
            atom_array.set_annotation(key, val.numpy())
        elif isinstance(val, list):
            # Legacy: older .pt files may have list annotations
            atom_array.set_annotation(key, np.array(val))

    return atom_array


# --- Round-trip verification --------------------------------------------------


def verify_round_trip(
    atom_array: AtomArray,
    *,
    tmp_dir: Path | None = None,
) -> tuple[bool, str]:
    """Save → load → compare: verify that round-trip is lossless.

    Args:
        atom_array: The original AtomArray to test.
        tmp_dir: Directory for the temporary .pt file (default: cwd).

    Returns:
        ``(passed, message)``.  ``passed=True`` when **every** annotation
        is identical between the original and the reloaded copy.
    """
    import tempfile

    tmp_dir = Path(tmp_dir) if tmp_dir is not None else Path(tempfile.gettempdir())
    tmp_dir.mkdir(parents=True, exist_ok=True)
    tmp_path = tmp_dir / f"_round_trip_verify_{id(atom_array)}.pt"

    try:
        save_atomarray_as_pt(atom_array, tmp_path)
        reloaded = load_atomarray_from_pt(tmp_path)

        # --- Compare atom count ---
        n_orig = len(atom_array)
        n_reloaded = len(reloaded)
        if n_orig != n_reloaded:
            return (False, f"atom count mismatch: {n_orig} vs {n_reloaded}")

        # --- Compare coord ---
        if not np.allclose(
            np.asarray(atom_array.coord),
            np.asarray(reloaded.coord),
            rtol=0, atol=0,
        ):
            return (False, "coord differs")

        # --- Compare every annotation ---
        orig_anns = set(atom_array.get_annotation_categories())
        reloaded_anns = set(reloaded.get_annotation_categories())
        if orig_anns != reloaded_anns:
            missing = orig_anns - reloaded_anns
            extra = reloaded_anns - orig_anns
            return (False, f"annotation mismatch: missing={missing}, extra={extra}")

        for ann in sorted(orig_anns):
            orig_val = np.asarray(getattr(atom_array, ann))
            reloaded_val = np.asarray(getattr(reloaded, ann))
            if orig_val.dtype != reloaded_val.dtype:
                return (
                    False,
                    f"dtype mismatch for '{ann}': {orig_val.dtype} vs {reloaded_val.dtype}",
                )
            if orig_val.shape != reloaded_val.shape:
                return (
                    False,
                    f"shape mismatch for '{ann}': {orig_val.shape} vs {reloaded_val.shape}",
                )
            if orig_val.dtype.kind in ("f", "c"):
                # Float types: exact match (NaN-safe)
                if not np.array_equal(
                    orig_val, reloaded_val, equal_nan=True
                ):
                    diff_count = int(
                        np.sum(
                            ~np.isclose(
                                orig_val,
                                reloaded_val,
                                rtol=0,
                                atol=0,
                                equal_nan=True,
                            )
                        )
                    )
                    return (
                        False,
                        f"value mismatch for '{ann}': {diff_count}/{orig_val.size} diffs",
                    )
            else:
                # Integer / string / bool types
                if not np.array_equal(orig_val, reloaded_val):
                    return (False, f"value mismatch for '{ann}'")

        # --- Compare bonds (if any) ---
        orig_bonds = atom_array.bonds
        reloaded_bonds = reloaded.bonds
        if orig_bonds is None and reloaded_bonds is not None:
            return (False, "bonds: original has None, reloaded has bonds")
        if orig_bonds is not None and reloaded_bonds is None:
            return (False, "bonds: original has bonds, reloaded has None")
        if orig_bonds is not None and reloaded_bonds is not None:
            if not np.array_equal(
                orig_bonds.as_array(), reloaded_bonds.as_array()
            ):
                return (False, "bonds differ")

        return (True, f"all {n_orig} atoms, {len(orig_anns)} annotations identical")

    except Exception as exc:
        return (False, f"exception: {type(exc).__name__}: {exc}")
    finally:
        tmp_path.unlink(missing_ok=True)


# --- Batch checkpoint verification --------------------------------------------


def verify_chunk_samples(
    cache_dir: Path,
    *,
    n_samples: int = 5,
    seed: int = 42,
) -> dict[str, Any]:
    """Randomly sample generated .pt files in *cache_dir* and verify round-trip.

    Returns a summary dict with per-file results.
    """
    rng = np.random.default_rng(seed)
    gt_files = sorted(cache_dir.glob("*_gt.pt"))
    monomer_files = sorted(cache_dir.glob("*_*_monomer.pt"))

    results: dict[str, Any] = {
        "cache_dir": str(cache_dir),
        "gt_files_found": len(gt_files),
        "monomer_files_found": len(monomer_files),
        "checks": [],
        "passed": 0,
        "failed": 0,
    }

    # Sample GT files
    if gt_files:
        sample_n = min(n_samples, len(gt_files))
        chosen = rng.choice(gt_files, size=sample_n, replace=False)
        for pt_path in sorted(chosen, key=lambda p: p.name):
            try:
                aa = load_atomarray_from_pt(pt_path)
                passed, msg = verify_round_trip(aa)
                results["checks"].append(
                    {"file": pt_path.name, "type": "gt", "passed": passed, "message": msg}
                )
                if passed:
                    results["passed"] += 1
                else:
                    results["failed"] += 1
            except Exception as exc:
                results["checks"].append(
                    {
                        "file": pt_path.name,
                        "type": "gt",
                        "passed": False,
                        "message": f"load failed: {exc}",
                    }
                )
                results["failed"] += 1

    # Sample monomer files
    if monomer_files:
        sample_n = min(n_samples, len(monomer_files))
        chosen = rng.choice(monomer_files, size=sample_n, replace=False)
        for pt_path in sorted(chosen, key=lambda p: p.name):
            try:
                aa = load_atomarray_from_pt(pt_path)
                passed, msg = verify_round_trip(aa)
                results["checks"].append(
                    {
                        "file": pt_path.name,
                        "type": "monomer",
                        "passed": passed,
                        "message": msg,
                    }
                )
                if passed:
                    results["passed"] += 1
                else:
                    results["failed"] += 1
            except Exception as exc:
                results["checks"].append(
                    {
                        "file": pt_path.name,
                        "type": "monomer",
                        "passed": False,
                        "message": f"load failed: {exc}",
                    }
                )
                results["failed"] += 1

    return results


# --- GT AtomArray ------------------------------------------------------------


def load_gt_atom_array(pt_path: Path) -> AtomArray | None:
    """Load the canonized GT AtomArray from a .pt cache file.

    Returns None if the file does not exist so callers can fall back to
    the original PDB parsing path.

    The returned AtomArray has been through:
      - PDB parsing
      - chain restriction (to sample chains)
      - heavy-atom canonicalization (H removal, MSE→MET, FME fix, CCD)
      - mol entity ID annotation

    It is ready for ``process_target_atom_array_of3`` (crop + tokenize).
    """
    if not pt_path.is_file():
        return None
    try:
        return load_atomarray_from_pt(pt_path)
    except Exception:
        return None


# --- Monomer AtomArrays ------------------------------------------------------


def load_monomer_atom_arrays(
    cache_dir: Path,
    case_id: str,
    chain_ids: list[str],
) -> dict[str, AtomArray]:
    """Load processed monomer AtomArrays for the given chains.

    Returns ``{chain_id: AtomArray}`` — a drop-in replacement for
    ``_load_mandatory_monomer_inputs()``.  Chains whose .pt files are
    missing are silently omitted from the result (the caller can detect
    this and fall back to PDB parsing for those chains).

    Each AtomArray has been through:
      - PDB parsing
      - heavy-atom canonicalization
      - mol entity ID annotation
      - process_target_atom_array_of3 (no-crop) + add_token_positions

    It is ready for ``build_monomer_input_geometry`` and
    ``_crop_monomer_template_to_query_tokens``.
    """
    result: dict[str, AtomArray] = {}
    for chain_id in chain_ids:
        pt_path = cache_dir / f"{case_id}_{chain_id}_monomer.pt"
        if not pt_path.is_file():
            continue
        try:
            result[chain_id] = load_atomarray_from_pt(pt_path)
        except Exception:
            continue
    return result


# --- Seq cache ---------------------------------------------------------------


def load_seq_cache_data(pt_path: Path) -> dict[str, Any] | None:
    """Load per-sample sequence metadata from a .pt cache file.

    Returns None if the file does not exist.

    Return format::
        {
            chain_id: {
                "full_seq_1aa": str,
                "full_seq_3aa": [str, ...],
                "resseq_to_sequence_index": {int: int},   # optional
            },
            ...
        }
    """
    if not pt_path.is_file():
        return None
    try:
        return torch.load(pt_path, map_location="cpu", weights_only=False)
    except Exception:
        return None


# --- Template precursor extraction (on-the-fly from loaded AtomArrays) ------


def extract_template_precursor(
    monomer_atom_arrays: dict[str, AtomArray],
) -> dict[str, dict[str, Any]]:
    """Extract per-residue template precursor tensors from monomer AtomArrays.

    This is a fast in-memory operation (numpy indexing + stacking).
    Does NOT do PDB I/O or atom canonicalization — those were already
    done by ``generate_pdb_tensors.py``.

    Args:
        monomer_atom_arrays: ``{chain_id: AtomArray}`` as returned by
            ``load_monomer_atom_arrays``.

    Returns:
        ``{chain_id: {res_id, res_name, pseudo_beta, pseudo_beta_mask,
        backbone_coords, backbone_frame_mask}}``

        Each value dict contains:
        - res_id:            Tensor[N_res]  int32
        - res_name:          list[str]       3-letter codes
        - pseudo_beta:       Tensor[N_res, 3]  float32  CB (or CA for GLY)
        - pseudo_beta_mask:  Tensor[N_res]    bool
        - backbone_coords:   Tensor[N_res, 3, 3]  float32  [N, CA, C]
        - backbone_frame_mask: Tensor[N_res]  bool

    These match the fields that ``create_template_feature_precursor_of3``
    fills into ``OF3TemplateFeaturePrecursor``, for one chain at a time.
    The caller is responsible for cropping to query token positions (using
    ``res_id`` ↔ query residue matching).
    """
    import biotite.structure as struc

    result: dict[str, dict[str, Any]] = {}

    for chain_id, atom_array in monomer_atom_arrays.items():
        residue_starts = struc.get_residue_starts(atom_array)
        residue_stops = np.append(residue_starts[1:], len(atom_array))
        n_res = len(residue_starts)

        res_ids = np.asarray(
            atom_array.res_id[residue_starts], dtype=np.int32
        )
        res_names_list = (
            np.asarray(atom_array.res_name[residue_starts])
            .astype(str)
            .tolist()
        )
        is_gly = np.array([rn == "GLY" for rn in res_names_list])

        n_coords = np.full((n_res, 3), np.nan, dtype=np.float32)
        ca_coords = np.full((n_res, 3), np.nan, dtype=np.float32)
        c_coords = np.full((n_res, 3), np.nan, dtype=np.float32)
        cb_coords = np.full((n_res, 3), np.nan, dtype=np.float32)

        atom_names_arr = np.asarray(atom_array.atom_name).astype(str)
        coords_arr = np.asarray(atom_array.coord, dtype=np.float32)

        for i, (start, stop) in enumerate(
            zip(residue_starts, residue_stops)
        ):
            for j in range(start, stop):
                name = atom_names_arr[j]
                if name == "N":
                    n_coords[i] = coords_arr[j]
                elif name == "CA":
                    ca_coords[i] = coords_arr[j]
                elif name == "C":
                    c_coords[i] = coords_arr[j]
                elif name == "CB":
                    cb_coords[i] = coords_arr[j]

        # Pseudo-beta: CB for non-GLY, CA for GLY
        pseudo_beta = np.where(
            is_gly[:, None], ca_coords, cb_coords
        ).astype(np.float32)
        pseudo_beta_mask = ~np.isnan(pseudo_beta).any(axis=-1)

        # Backbone frame: [N, CA, C] → [N_res, 3, 3]
        backbone_coords = np.stack(
            [n_coords, ca_coords, c_coords], axis=1
        ).astype(np.float32)
        backbone_frame_mask = ~np.isnan(backbone_coords).any(axis=(-2, -1))

        result[chain_id] = {
            "res_id": torch.from_numpy(res_ids),
            "res_name": res_names_list,
            "pseudo_beta": torch.from_numpy(
                np.nan_to_num(pseudo_beta, nan=0.0)
            ),
            "pseudo_beta_mask": torch.from_numpy(pseudo_beta_mask),
            "backbone_coords": torch.from_numpy(
                np.nan_to_num(backbone_coords, nan=0.0)
            ),
            "backbone_frame_mask": torch.from_numpy(backbone_frame_mask),
        }

    return result


# --- Path derivation (mirrors _runtime.py's _derive_pt_path) -----------------

_MESH_PT_DATASET_MAP = {
    "afdb": "AFDB-10k-1",
    "qbiolip": "Q-BioLiP-10k-new",
}


def derive_cache_dir(
    prior_pkl: Path,
    dataset_name: str,
    cache_root_name: str = "precomputed_mesh/cli_v3",
) -> Path | None:
    """Derive the pdb_cache directory from a sample's prior_pkl path.

    Uses the same logic as ``_runtime._derive_pt_path`` /
    ``_build_surface_mesh_prior``.

    Example::

        prior_pkl = .../training/AFDB-10k-1/chunk/chunk0008/prior_pkl/AF-xxx.pkl
        → .../training/precomputed_mesh/cli_v3/AFDB-10k-1/chunk0008/

    """
    dataset_dir = _MESH_PT_DATASET_MAP.get(dataset_name)
    if dataset_dir is None:
        return None
    try:
        chunk_name = prior_pkl.parent.parent.name  # chunkXXXX
        dataset_root = prior_pkl.parent.parent.parent.parent.parent
        return dataset_root / cache_root_name / dataset_dir / chunk_name
    except Exception:
        return None
